'''
Train and test the models of the NeSy compliance experiments.

    python main.py --dataset sepsis                                # default configurations, LSTM backbone
    python main.py --dataset bpi12 --configs vanilla ltn B ABC     # a subset
    python main.py --dataset traffic --model transformer --seeds 0 1 2

Configurations (--configs, see nesy/training.py):
    vanilla    backbone trained with binary cross-entropy (BCE)
    feat_eng   backbone with the rule truth values as extra inputs, BCE
    semantic   backbone, BCE + semantic loss on the rules
    ltn        LTN with the data axioms only
    A, B, C, AB, AC, BC, ABC   LTN with knowledge: A = logical rules as inputs of P, B = logical rules as
                               axioms on P, C = Declare (control-flow) constraints, never connected to the label:
                               inputs of P (default) or, with --no-declare_in_p, axioms Forall x: C(x);
                               by default the best constraints mined on the training prefixes, with
                               --declare_source predefined the hand-written ones of knowledge_base.txt
The rules of each dataset are defined once, in nesy/knowledge.py (Declare rules: nesy/declare_knowledge.py);
knowledge_base.txt describes them, with statistics, and is generated by make_knowledge_base.py.

Old scripts (legacy/) -> new command:
    main_<dataset>_compliance.py           --dataset <dataset> --configs vanilla ltn B A AB BC AC ABC
    main_<dataset>_feat_eng.py             --dataset <dataset> --configs feat_eng
    main_<dataset>_semantic(_loss).py      --dataset <dataset> --configs semantic
    main_traffic_compliance_transformer.py --dataset traffic --model transformer
    main_sepsis_compliance_declare.py      --dataset sepsis

Protocol: for every seed, each configuration is trained from the same initial seed and the same batch order,
the parameters with the best validation macro-F1 are kept (early stopping with --patience), and the model is
tested once. The split is fixed by the seeded preprocessing (data/preprocess_<dataset>.py).
Results: results/runs/<dataset>_<model>_<timestamp>.json (arguments, rules, all metrics) and one row per
(seed, configuration) appended to results/results.csv.
'''
import argparse
import csv
import json
import math
import os
import platform
import statistics
import time

os.environ.setdefault("CUBLAS_WORKSPACE_CONFIG", ":4096:8")  # deterministic cuBLAS, before CUDA is initialized

import ltn
import torch

from nesy.datasets import DATASETS, load_dataset, make_loader
from nesy.declare_knowledge import add_declare_args, build_declare_knowledge
from nesy.evaluation import METRICS, evaluate
from nesy.knowledge import build_knowledge
from nesy.training import (CONFIGS, LTNLoss, ModelInput, bce_loss, build_model, fit, parse_configuration,
                           semantic_rule_loss, set_seed)

DEFAULT_CONFIGS = ["vanilla", "feat_eng", "semantic", "ltn", "A", "B", "AB", "BC", "AC", "ABC"]


def get_args():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", required=True, choices=DATASETS)
    parser.add_argument("--model", default="lstm", choices=["lstm", "transformer"], help="Backbone / neural predicate P")
    parser.add_argument("--configs", nargs="+", default=DEFAULT_CONFIGS, choices=CONFIGS + ["all"],
                        help=f"Configurations to train and test (default: {' '.join(DEFAULT_CONFIGS)})")
    parser.add_argument("--seeds", type=int, nargs="+", default=[42], help="One run of every configuration per seed")
    parser.add_argument("--device", default="cuda:0" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--output_dir", default="results")

    training = parser.add_argument_group("training")
    training.add_argument("--epochs", type=int, default=15, help="Maximum epochs of vanilla, feat_eng and semantic")
    training.add_argument("--epochs_ltn", type=int, default=None,
                          help="Maximum epochs of the LTN configurations (default: per dataset, see nesy/datasets.py)")
    training.add_argument("--patience", type=int, default=5, help="Early stopping on the validation macro-F1")
    training.add_argument("--batch_size", type=int, default=32)
    training.add_argument("--lr", type=float, default=1e-3)
    training.add_argument("--lambda_sem", type=float, default=0.1, help="Weight of the semantic loss")

    network = parser.add_argument_group("network")
    network.add_argument("--hidden_size", type=int, default=128, help="LSTM hidden size (and embedding size)")
    network.add_argument("--model_dim", type=int, default=64, help="Transformer model dimension (and embedding size)")
    network.add_argument("--num_heads", type=int, default=4, help="Transformer attention heads")
    network.add_argument("--num_layers", type=int, default=2)
    network.add_argument("--dropout", type=float, default=0.1)

    add_declare_args(parser)
    args = parser.parse_args()
    # Canonical order, without duplicates
    args.configs = CONFIGS if "all" in args.configs else [c for c in CONFIGS if c in args.configs]
    if args.epochs_ltn is None:
        args.epochs_ltn = DATASETS[args.dataset].epochs_ltn
    return args


def run_configuration(name, args, data, knowledge, declare, seed):
    '''Train one configuration from `seed` and return its test metrics.'''
    config = parse_configuration(name, args.declare_in_p)
    model_input = ModelInput(config, knowledge, declare)
    set_seed(seed)
    model = build_model(args, data, num_rule_features=model_input.num_features).to(args.device)
    if config.loss == "ltn":
        loss_fn, epochs = LTNLoss(ltn.Predicate(model), model_input, knowledge, config, declare), args.epochs_ltn
    elif config.loss == "semantic":
        loss_fn, epochs = semantic_rule_loss(model, knowledge, args.lambda_sem), args.epochs
    else:
        loss_fn, epochs = bce_loss(model, model_input), args.epochs
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)
    train_loader = make_loader(data.train, args.batch_size, shuffle=True, seed=seed)
    val_loader = make_loader(data.val, args.batch_size)
    test_loader = make_loader(data.test, args.batch_size)

    def validate():
        return evaluate(model, val_loader, knowledge, model_input, args.device)["f1"]

    fit(model, loss_fn, optimizer, train_loader, validate, epochs, args.patience, args.device, name)
    return evaluate(model, test_loader, knowledge, model_input, args.device)


def print_table(results, configs):
    '''Test metrics per configuration, mean ± std over the seeds.'''
    columns = [m for m in METRICS if any(m in r[c] for r in results.values() for c in configs)]
    print("\n" + f"{'config':<10}" + "".join(f"{m:>22}" for m in columns))
    for name in configs:
        row = f"{name:<10}"
        for metric in columns:
            values = [r[name][metric] for r in results.values() if not math.isnan(r[name].get(metric, math.nan))]
            if not values:
                row += f"{'n/a':>22}"
            elif len(values) == 1:
                row += f"{values[0]:>22.4f}"
            else:
                row += f"{statistics.mean(values):>13.4f} ± {statistics.stdev(values):.4f}"
        print(row)


def save_results(args, knowledge, declare, results):
    timestamp = time.strftime("%Y%m%d-%H%M%S")
    os.makedirs(os.path.join(args.output_dir, "runs"), exist_ok=True)
    path = os.path.join(args.output_dir, "runs", f"{args.dataset}_{args.model}_{timestamp}.json")
    with open(path, "w") as f:
        json.dump({
            "args": vars(args),
            "versions": {"python": platform.python_version(), "torch": torch.__version__},
            "rules": [{"name": r.name, "label": r.label, "constraint_only": r.constraint_only} for r in knowledge.rules],
            "declare_constraints": [str(c) for c in declare.constraints] if declare else None,
            "results": {str(seed): metrics for seed, metrics in results.items()},
        }, f, indent=2)

    table = os.path.join(args.output_dir, "results.csv")
    new_file = not os.path.exists(table)
    with open(table, "a", newline="") as f:
        writer = csv.writer(f)
        if new_file:
            writer.writerow(["timestamp", "dataset", "model", "seed", "config"] + METRICS)
        for seed, metrics in results.items():
            for name, m in metrics.items():
                writer.writerow([timestamp, args.dataset, args.model, seed, name] + [m.get(k, "") for k in METRICS])
    print(f"\n-- Results saved to {path} and {table}")


def main():
    args = get_args()
    print(f"-- {args.dataset} | model {args.model} | configurations {args.configs} | seeds {args.seeds} | "
          f"device {args.device}")
    data = load_dataset(args.dataset)
    knowledge = build_knowledge(data)
    knowledge.print_summary(data.train.sequences, data.train.labels)
    declare = None
    if any("C" in c for c in args.configs):
        os.makedirs(args.output_dir, exist_ok=True)
        declare_path = os.path.join(args.output_dir, f"declare_{args.dataset}_{args.declare_source}.json")
        declare = build_declare_knowledge(data, args, declare_path)

    results = {}
    for seed in args.seeds:
        results[seed] = {}
        for name in args.configs:
            print(f"\n-- Training {name} (seed {seed})")
            results[seed][name] = run_configuration(name, args, data, knowledge, declare, seed)
            print("   test: " + ", ".join(f"{m} {results[seed][name][m]:.4f}"
                                          for m in METRICS if m in results[seed][name]))
    print_table(results, args.configs)
    save_results(args, knowledge, declare, results)


if __name__ == "__main__":
    main()
